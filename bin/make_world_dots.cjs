#!/usr/bin/env node
// Generates _includes/world_dots.liquid: the dotted world land of the collaboration
// map on the home page (_includes/collaboration_map.liquid). Run once; the land
// doesn't change. Not part of the website build.
//
//   npm install --no-save world-atlas@2 topojson-client@3 d3-geo@3   (in any folder)
//   NODE_PATH=<that folder>/node_modules node bin/make_world_dots.cjs > _includes/world_dots.liquid
//
// Land: Natural Earth 110 m (public domain), via the world-atlas package.
// Projection: equirectangular, 1000 units wide, latitudes 84°N (top) to 57°S (bottom):
//   x = (lon + 180) * 1000 / 360,   y = (84 - lat) * 1000 / 360   → height 391.67
// The same formula places the markers in collaboration_map.liquid.
// Dots sit on a staggered grid and are drawn as one path of zero-length segments
// ("M x y h0"); with round line caps each segment shows as a round dot.

const { feature } = require("topojson-client");
const { geoContains } = require("d3-geo");
const land = feature(require("world-atlas/land-110m.json"), require("world-atlas/land-110m.json").objects.land);

const K = 1000 / 360; // map units per degree
const TOP = 84;
const HEIGHT = (TOP + 57) * K;
const STEP = 6.25; // distance between dots, in map units

const parts = [];
let row = 0;
for (let y = STEP / 2; y < HEIGHT; y += STEP * 0.87, row++) {
  const shift = row % 2 ? STEP / 2 : 0;
  for (let x = STEP / 2 + shift; x < 1000; x += STEP) {
    const lon = x / K - 180;
    const lat = TOP - y / K;
    if (geoContains(land, [lon, lat])) parts.push(`M${x.toFixed(1)} ${y.toFixed(1)}h0`);
  }
}

process.stdout.write(
  "{%- comment -%}\n" +
    "  GENERATED by bin/make_world_dots.cjs (see there) from Natural Earth 110 m land.\n" +
    `  ${parts.length} dots, equirectangular 1000 x ${HEIGHT.toFixed(2)}, 84°N to 57°S. Do not edit by hand.\n` +
    "{%- endcomment -%}\n" +
    `<path class="collab-map__land" d="${parts.join("")}"/>\n`
);
